    private static $allCountries;


    static function parseCode(string $countryName)
    {
        $countryName = trim($countryName);

        $code = self::findByCountries($countryName);
        return $code ?? self::findInDics($countryName) ?? null;
    }

    private static function findByCountries($name)
    {
        if (!self::$allCountries) {
            self::$allCountries = Countries::all();
        }
        foreach (self::$allCountries as $country) {
            foreach (self::getAllNamesOfCountry($country) as $countryName) {
                if (str_contains(strtolower($countryName), strtolower($name)) && isset($country->iso_a2)) {
                    return $country->iso_a2;
                }
            }
        }
        return null;
    }

    static function getAllNamesOfCountry($country)
    {
        $array = [];
        if (isset($country->name)) {
            $array = array_merge($array, self::getNames($country->name));
        }
        if (isset($country->alt_spellings)) {
            $array = array_merge($array, self::getNames($country->alt_spellings));
        }

        return array_unique($array);
    }

    static function getNames(iterable $array)
    {
        $res = [];
        foreach ($array as $key => $value) {
            if (is_iterable($value)) {
                $res = array_merge($res, self::getNames($value));
            } else {
                $res[] = $value;
            }
        }
        return $res;
    }

    private static function findInDics(string $name): ?string
    {
        foreach (self::$dics as $dic) {
            $res = self::findInDic($name, $dic);
            if ($res) return $res;
        }
        return null;
    }

    static private function findInDic(string $name, array $dic): ?string
    {
        foreach ($dic as $dicName => $dicCode) {
            if (str_contains(strtolower($dicName), strtolower($name))) {
                return $dicCode;
            }
        }
        return null;
    }
